#!/usr/bin/env node
// build-captions.mjs — turn ElevenLabs word timings into (a) karaoke caption
// chunks for a Remotion component and (b) a real .srt sidecar.
//
//   node scripts/build-captions.mjs <config.json>
//
// config.json:
// {
//   "voDir":      "out/voExp",            // holds <id>.words.json from eleven-vo-ts.mjs
//   "offsets":    { "s01": 0.9, "s02": 9.9, ... },   // absolute video seconds per line.
//                                          // MUST match the adelay values in your mux.
//   "out":        "src/captions-exp.ts",
//   "exportName": "CAPTIONS_EXP",
//   "chunk":      4,                       // words per pill. Use 3 for 9:16.
//   "srt":        "out/name.srt",          // optional
//   "script":     "tmp/vo-lines.json"      // optional; enables SENTENCE-level srt
// }
//
// Why `script` matters: karaoke chunks are 4-word ALL-CAPS fragments with
// punctuation stripped — correct on screen, terrible as a subtitle track. Given
// the original lines, the .srt is rebuilt from real sentences instead.
import fs from "fs";

const cfg = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const CHUNK = cfg.chunk ?? 4;
const words = (id) => JSON.parse(fs.readFileSync(`${cfg.voDir}/${id}.words.json`, "utf8"));

// ---- karaoke chunks --------------------------------------------------------
const chunks = [];
for (const [id, off] of Object.entries(cfg.offsets)) {
  const ws = words(id);
  for (let i = 0; i < ws.length; i += CHUNK) {
    const grp = ws.slice(i, i + CHUNK).map((w) => ({
      w: w.word.replace(/[.,!?;:'"]+$/g, "").toUpperCase(),
      s: +(off + w.start).toFixed(3),
      e: +(off + w.end).toFixed(3),
    }));
    if (grp.length) chunks.push({ t0: grp[0].s, t1: +(grp.at(-1).e + 0.25).toFixed(3), words: grp });
  }
}
chunks.sort((a, b) => a.t0 - b.t0);
for (let i = 0; i < chunks.length - 1; i++) if (chunks[i].t1 > chunks[i + 1].t0) chunks[i].t1 = chunks[i + 1].t0;

fs.writeFileSync(cfg.out, `// AUTO-GENERATED by scripts/build-captions.mjs — do not edit by hand.
export type CWord = { w: string; s: number; e: number };
export type CChunk = { t0: number; t1: number; words: CWord[] };
export const ${cfg.exportName}: CChunk[] = ${JSON.stringify(chunks)};
`);
const txt = chunks.map((c) => c.words.map((w) => w.w).join(" "));
console.log(`${chunks.length} chunks, last ends ${chunks.at(-1).t1}s`);
console.log("longest:", [...txt].sort((a, b) => b.length - a.length)[0]);
const durs = chunks.map((c) => c.t1 - c.t0);
console.log(`onscreen sec: min ${Math.min(...durs).toFixed(2)} avg ${(durs.reduce((a, b) => a + b) / durs.length).toFixed(2)}`);

// ---- .srt sidecar ----------------------------------------------------------
if (!cfg.srt) process.exit(0);
const ts = (t) => {
  const h = Math.floor(t / 3600), m = Math.floor((t % 3600) / 60), s = Math.floor(t % 60), ms = Math.round((t % 1) * 1000);
  return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")},${String(ms).padStart(3, "0")}`;
};

let cues;
if (cfg.script) {
  // sentence-level: proper case + punctuation, timed by consuming the alignment
  const byId = Object.fromEntries(JSON.parse(fs.readFileSync(cfg.script, "utf8")).map((l) => [l.id, l.text]));
  const sentences = [];
  for (const [id, off] of Object.entries(cfg.offsets)) {
    const ws = words(id);
    let cur = 0;
    for (const sent of (byId[id] || "").match(/[^.!?]+[.!?]*/g)?.map((s) => s.trim()).filter(Boolean) ?? []) {
      const grp = ws.slice(cur, cur + sent.split(/\s+/).length);
      cur += sent.split(/\s+/).length;
      if (grp.length) sentences.push({ text: sent, s: off + grp[0].start, e: off + grp.at(-1).end });
    }
  }
  cues = [];
  for (const sn of sentences) {
    const last = cues.at(-1);
    if (last && (last.text + " " + sn.text).length <= 90 && sn.e - last.s <= 6 && sn.s - last.e < 1.0) {
      last.text += " " + sn.text; last.e = sn.e;
    } else cues.push({ ...sn });
  }
} else {
  cues = chunks.map((c) => ({ text: c.words.map((w) => w.w).join(" "), s: c.t0, e: c.t1 }));
}
for (let i = 0; i < cues.length - 1; i++) cues[i].e = Math.min(cues[i].e + 0.35, cues[i + 1].s - 0.02);
fs.writeFileSync(cfg.srt, cues.map((c, i) => `${i + 1}\n${ts(c.s)} --> ${ts(c.e)}\n${c.text}\n`).join("\n"));
console.log(`srt: ${cues.length} cues -> ${cfg.srt}${cfg.script ? " (sentence-level)" : " (chunk-level — pass `script` for better)"}`);
